import type { GridSize } from '../engine/types';

export type TemplateCategory =
  | 'Animals'
  | 'Food'
  | 'Space'
  | 'Vehicles'
  | 'Festivals'
  | 'Sports'
  | 'Faces'
  | 'Letters & Numbers';

export interface PixelTemplate {
  id: string;
  name: string;
  category: TemplateCategory;
  size: GridSize;
  emoji: string;
  /** Row-major array of DEFAULT_PIXEL_PALETTE 1-based indices (0 = transparent). */
  pixels: number[];
}

// Palette 1-based index legend for DEFAULT_PIXEL_PALETTE:
// . = 0 (transparent)
// K = 1 (Black #111827)   W = 2 (White #FFFFFF)   N = 3 (Navy #1E293B)
// B = 4 (Royal Blue)      S = 5 (Sky Blue)        T = 6 (Teal)
// G = 7 (Meadow Green)    L = 8 (Lime)            Y = 9 (Sunny Yellow)
// O = 10 (Tangerine)      R = 11 (Cherry Red)     P = 12 (Bubblegum Pink)
// Q = 13 (Soft Rose)      U = 14 (Grape Purple)   V = 15 (Lavender)
// C = 16 (Light Peach)    A = 17 (Warm Tan)       M = 18 (Cocoa Brown)
// E = 19 (Slate Grey)     I = 20 (Cloud Silver)
const CHAR_TO_INDEX: Record<string, number> = {
  '.': 0,
  K: 1,
  W: 2,
  N: 3,
  B: 4,
  S: 5,
  T: 6,
  G: 7,
  L: 8,
  Y: 9,
  O: 10,
  R: 11,
  P: 12,
  Q: 13,
  U: 14,
  V: 15,
  C: 16,
  A: 17,
  M: 18,
  E: 19,
  I: 20,
};

function parseTemplate(rows: string[], size: GridSize): number[] {
  const out = new Array<number>(size * size).fill(0);
  for (let y = 0; y < Math.min(size, rows.length); y++) {
    const row = rows[y];
    for (let x = 0; x < Math.min(size, row.length); x++) {
      out[y * size + x] = CHAR_TO_INDEX[row[x]] ?? 0;
    }
  }
  return out;
}

