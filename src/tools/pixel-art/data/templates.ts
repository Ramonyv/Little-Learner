const DAILY_CHALLENGES = [
  'Today: draw something that flies!',
  'Today: draw your favorite fruit!',
  'Today: draw a rocket in space!',
  'Today: draw a bright Diwali diya!',
  'Today: draw a friendly ocean animal!',
  'Today: draw a fast race car!',
  'Today: draw a happy sun!',
];

export function getDailyPixelChallenge(): string {
  const now = new Date();
  const day = Math.floor(
    (now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / 86400000,
  );
  return DAILY_CHALLENGES[day % DAILY_CHALLENGES.length];
}
